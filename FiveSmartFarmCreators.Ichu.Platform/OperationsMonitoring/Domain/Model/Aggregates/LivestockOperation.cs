using FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Model.Errors;
using FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Model.ValueObjects;
using FiveSmartFarmCreators.Ichu.Platform.Shared.Application.Model;
using FiveSmartFarmCreators.Ichu.Platform.Shared.Domain.Model.Aggregates.Internal;
using FiveSmartFarmCreators.Ichu.Platform.Shared.Domain.Model.Errors;

namespace FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Model.Aggregates;

/// <summary>
///     A field event observed by an operator or a clinical intervention applied by a veterinarian. Its identifier is the operation identifier generated by the client, so offline retries never create a second record.
/// </summary>
public sealed class LivestockOperation : AggregateRoot
{
    public const int MaximumObservationLength = 500;

    public const int MaximumProductLength = 120;

    public const int MaximumDoseLength = 60;

    // Entity Framework Core materializes operations without running the factory.
    private LivestockOperation()
    {
    }

    public LivestockOperationId Id { get; private set; }

    public Guid RanchId { get; private set; }

    public Guid CattleId { get; private set; }

    public OperationType Type { get; private set; }

    public DateTimeOffset OccurredAt { get; private set; }

    public DateTimeOffset ReceivedAt { get; private set; }

    public Guid AuthorId { get; private set; }

    public string? Observation { get; private set; }

    public string? Product { get; private set; }

    public string? Dose { get; private set; }

    public static Result<LivestockOperation> Create(
        Guid operationId,
        Guid ranchId,
        Guid cattleId,
        OperationType type,
        DateTimeOffset occurredAt,
        Guid authorId,
        string? observation,
        string? product,
        string? dose,
        DateTimeOffset receivedAt)
    {
        if (operationId == Guid.Empty || ranchId == Guid.Empty || cattleId == Guid.Empty || authorId == Guid.Empty)
        {
            return Result<LivestockOperation>.Failure(OperationsMonitoringErrors.LivestockIdentifiersRequired);
        }

        var normalizedProduct = NormalizeOptional(product, MaximumProductLength, OperationsMonitoringErrors.ProductTooLong);
        if (normalizedProduct.IsFailure)
        {
            return Result<LivestockOperation>.Failure(normalizedProduct.DomainError);
        }

        var normalizedDose = NormalizeOptional(dose, MaximumDoseLength, OperationsMonitoringErrors.DoseTooLong);
        if (normalizedDose.IsFailure)
        {
            return Result<LivestockOperation>.Failure(normalizedDose.DomainError);
        }

        if (!IsClinical(type) && (normalizedProduct.Value is not null || normalizedDose.Value is not null))
        {
            return Result<LivestockOperation>.Failure(OperationsMonitoringErrors.ProductOrDoseNotClinical);
        }

        var normalizedObservation = NormalizeOptional(observation, MaximumObservationLength, OperationsMonitoringErrors.ObservationTooLong);
        if (normalizedObservation.IsFailure)
        {
            return Result<LivestockOperation>.Failure(normalizedObservation.DomainError);
        }

        return Result<LivestockOperation>.Success(new LivestockOperation
        {
            Id = new LivestockOperationId(operationId),
            RanchId = ranchId,
            CattleId = cattleId,
            Type = type,
            OccurredAt = MonitoringTime.Normalize(occurredAt),
            ReceivedAt = MonitoringTime.Normalize(receivedAt),
            AuthorId = authorId,
            Observation = normalizedObservation.Value,
            Product = normalizedProduct.Value,
            Dose = normalizedDose.Value
        });
    }

    public static bool IsClinical(OperationType type) =>
        type is OperationType.Vaccination or OperationType.Treatment or OperationType.Insemination;

    // A retry repeats the same content; the stored record is returned instead of a second one.
    public bool HasSameContentAs(LivestockOperation other) =>
        Id == other.Id &&
        CattleId == other.CattleId &&
        Type == other.Type &&
        OccurredAt == other.OccurredAt &&
        AuthorId == other.AuthorId &&
        Observation == other.Observation &&
        Product == other.Product &&
        Dose == other.Dose;

    private static Result<string?> NormalizeOptional(string? value, int maximumLength, Error tooLong)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            return Result<string?>.Success(null);
        }

        var normalized = value.Trim();
        return normalized.Length > maximumLength
            ? Result<string?>.Failure(tooLong)
            : Result<string?>.Success(normalized);
    }
}
