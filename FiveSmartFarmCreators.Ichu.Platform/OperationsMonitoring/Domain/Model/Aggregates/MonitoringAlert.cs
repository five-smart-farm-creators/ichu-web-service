using FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Model.Entities;
using FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Model.ValueObjects;

namespace FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Model.Aggregates;

/// <summary>
///     Aggregate root representing an alert evaluated by an Edge Gateway and synchronized with a stable identifier.
///     The alert is raised at the capture time of its triggering reading, and every supporting reading must satisfy
///     the alert condition.
/// </summary>
public class MonitoringAlert
{
    /// <summary>Maximum number of characters of a finding or an action.</summary>
    public const int MaximumTextLength = 400;

    /// <summary>Window in which new evidence of the same condition joins the open alert instead of raising another.</summary>
    public static readonly TimeSpan DeduplicationWindow = TimeSpan.FromHours(6);

    // Separates the fields of the operation data so that different field values never produce the same text.
    private const char FieldSeparator = '\u001F';

    private readonly List<AlertEvidence> _evidence = [];
    private readonly List<AlertChange> _changes = [];

    private MonitoringAlert()
    {
    }

    private MonitoringAlert(
        Guid alertId,
        AlertType type,
        AlertSeverity severity,
        long configurationRevision,
        Guid gatewayId,
        IReadOnlyList<TelemetryReading> supportingReadings,
        DateTimeOffset receivedAt)
    {
        if (alertId == Guid.Empty || gatewayId == Guid.Empty)
        {
            throw new ArgumentException("Alert and gateway identifiers are required.");
        }

        if (configurationRevision < 1)
        {
            throw new ArgumentException("An alert must reference the configuration revision used to evaluate it.");
        }

        if (supportingReadings.Count == 0)
        {
            throw new ArgumentException("An alert requires at least one supporting reading.");
        }

        var trigger = supportingReadings[0];
        if (trigger.CattleId is not { } cattleId)
        {
            throw new ArgumentException("Alert evidence must be attributed to an animal.");
        }

        Id = alertId;
        RanchId = trigger.RanchId;
        CattleId = cattleId;
        DeviceId = trigger.DeviceId;
        TriggerReadingId = trigger.ReadingId;
        GatewayId = gatewayId;
        Type = type;
        Severity = severity;
        Status = AlertStatus.Pending;
        ConfigurationRevision = configurationRevision;
        RaisedAt = trigger.RecordedAt;
        ReceivedAt = MonitoringTime.Normalize(receivedAt);
        Version = 1;
    }

    /// <summary>Gets the stable alert identifier generated by the Edge Gateway.</summary>
    public Guid Id { get; private set; }

    /// <summary>Gets the ranch that owns the animal.</summary>
    public Guid RanchId { get; private set; }

    /// <summary>Gets the animal the alert refers to.</summary>
    public Guid CattleId { get; private set; }

    /// <summary>Gets the device that captured the triggering reading.</summary>
    public Guid DeviceId { get; private set; }

    /// <summary>Gets the reading that triggered the alert.</summary>
    public Guid TriggerReadingId { get; private set; }

    /// <summary>Gets the Edge Gateway that evaluated the alert.</summary>
    public Guid GatewayId { get; private set; }

    /// <summary>Gets the condition that raised the alert.</summary>
    public AlertType Type { get; private set; }

    /// <summary>Gets the severity of the alert.</summary>
    public AlertSeverity Severity { get; private set; }

    /// <summary>Gets whether the alert has received attention.</summary>
    public AlertStatus Status { get; private set; }

    /// <summary>Gets the value that exceeded the threshold, for threshold alerts.</summary>
    public double? DetectedValue { get; private set; }

    /// <summary>Gets the lower bound of the evaluated threshold, for threshold alerts.</summary>
    public double? ThresholdMinValue { get; private set; }

    /// <summary>Gets the upper bound of the evaluated threshold, for threshold alerts.</summary>
    public double? ThresholdMaxValue { get; private set; }

    /// <summary>Gets the rule revision used to evaluate the alert.</summary>
    public long ConfigurationRevision { get; private set; }

    /// <summary>Gets the geofence that was left, for geofence alerts.</summary>
    public Guid? GeofenceId { get; private set; }

    /// <summary>Gets the latitude of the triggering position, for geofence alerts.</summary>
    public double? Latitude { get; private set; }

    /// <summary>Gets the longitude of the triggering position, for geofence alerts.</summary>
    public double? Longitude { get; private set; }

    /// <summary>Gets the distance in meters from the triggering position to the boundary, for geofence alerts.</summary>
    public double? DistanceToBoundaryMeters { get; private set; }

    /// <summary>Gets the capture time of the triggering reading.</summary>
    public DateTimeOffset RaisedAt { get; private set; }

    /// <summary>Gets the instant the cloud received the alert.</summary>
    public DateTimeOffset ReceivedAt { get; private set; }

    /// <summary>Gets the instant the animal returned to the permitted area, for geofence alerts.</summary>
    public DateTimeOffset? ClearedAt { get; private set; }

    /// <summary>Gets the instant the alert received attention.</summary>
    public DateTimeOffset? AcknowledgedAt { get; private set; }

    /// <summary>Gets the account that attended the alert.</summary>
    public Guid? AcknowledgedBy { get; private set; }

    /// <summary>Gets the finding recorded when the alert was attended.</summary>
    public string? Finding { get; private set; }

    /// <summary>Gets the action recorded when the alert was attended.</summary>
    public string? Action { get; private set; }

    /// <summary>Gets the version used to detect stale attention requests.</summary>
    public int Version { get; private set; }

    /// <summary>Gets the readings that support the alert.</summary>
    public IReadOnlyCollection<AlertEvidence> Evidence => _evidence;

    /// <summary>Gets the operations applied to the alert.</summary>
    public IReadOnlyCollection<AlertChange> Changes => _changes;

    /// <summary>Gets the evaluated threshold of a threshold alert.</summary>
    public ThresholdRange? Threshold => ThresholdMinValue is { } min && ThresholdMaxValue is { } max
        ? new ThresholdRange(min, max)
        : null;

    /// <summary>Gets the time between the alert event and its attention.</summary>
    public TimeSpan? ResponseTime => AcknowledgedAt - RaisedAt;

    /// <summary>Gets the time between the alert event and the return to the permitted area.</summary>
    public TimeSpan? ExitDuration => ClearedAt - RaisedAt;

    /// <summary>
    ///     Raises an alert for a metric that exceeded its configured threshold.
    /// </summary>
    /// <param name="alertId">The alert identifier generated by the Edge Gateway.</param>
    /// <param name="type">The threshold alert type.</param>
    /// <param name="severity">The alert severity.</param>
    /// <param name="threshold">The threshold used by the gateway to evaluate the alert.</param>
    /// <param name="configurationRevision">The rule revision used to evaluate the alert.</param>
    /// <param name="gatewayId">The Edge Gateway that evaluated the alert.</param>
    /// <param name="supportingReadings">The supporting readings; the first one triggers the alert.</param>
    /// <param name="receivedAt">The instant the cloud received the alert.</param>
    /// <returns>The new pending alert.</returns>
    /// <exception cref="ArgumentException">Thrown when the alert data or its evidence is invalid.</exception>
    public static MonitoringAlert RaiseForThreshold(
        Guid alertId,
        AlertType type,
        AlertSeverity severity,
        ThresholdRange threshold,
        long configurationRevision,
        Guid gatewayId,
        IReadOnlyList<TelemetryReading> supportingReadings,
        DateTimeOffset receivedAt)
    {
        var metric = MetricFor(type);
        var alert = new MonitoringAlert(alertId, type, severity, configurationRevision, gatewayId, supportingReadings, receivedAt)
        {
            ThresholdMinValue = threshold.MinValue,
            ThresholdMaxValue = threshold.MaxValue,
            DetectedValue = supportingReadings[0].MeasurementOf(metric).Value
        };
        alert.AttachEvidence(supportingReadings);
        return alert;
    }

    /// <summary>
    ///     Raises an alert for an animal that left its permitted area.
    /// </summary>
    /// <param name="alertId">The alert identifier generated by the Edge Gateway.</param>
    /// <param name="severity">The alert severity.</param>
    /// <param name="geofenceId">The geofence that was left.</param>
    /// <param name="distanceToBoundaryMeters">The distance in meters from the triggering position to the boundary.</param>
    /// <param name="configurationRevision">The rule revision used to evaluate the alert.</param>
    /// <param name="gatewayId">The Edge Gateway that evaluated the alert.</param>
    /// <param name="supportingReadings">The supporting readings; the first one triggers the alert.</param>
    /// <param name="receivedAt">The instant the cloud received the alert.</param>
    /// <returns>The new pending alert.</returns>
    /// <exception cref="ArgumentException">Thrown when the alert data or its evidence is invalid.</exception>
    public static MonitoringAlert RaiseForGeofence(
        Guid alertId,
        AlertSeverity severity,
        Guid geofenceId,
        double distanceToBoundaryMeters,
        long configurationRevision,
        Guid gatewayId,
        IReadOnlyList<TelemetryReading> supportingReadings,
        DateTimeOffset receivedAt)
    {
        if (geofenceId == Guid.Empty)
        {
            throw new ArgumentException("A geofence alert must reference its geofence.");
        }

        if (!double.IsFinite(distanceToBoundaryMeters) || distanceToBoundaryMeters < 0)
        {
            throw new ArgumentException("The distance to the geofence boundary must be a non-negative number of meters.");
        }

        var alert = new MonitoringAlert(alertId, AlertType.Geofence, severity, configurationRevision, gatewayId, supportingReadings, receivedAt)
        {
            GeofenceId = geofenceId,
            DistanceToBoundaryMeters = distanceToBoundaryMeters,
            Latitude = supportingReadings[0].Position.Latitude,
            Longitude = supportingReadings[0].Position.Longitude
        };
        alert.AttachEvidence(supportingReadings);
        return alert;
    }

    /// <summary>
    ///     Gets the metric that a threshold alert type is evaluated against.
    /// </summary>
    /// <param name="type">The alert type.</param>
    /// <returns>The monitored metric.</returns>
    /// <exception cref="ArgumentException">Thrown when the alert type is not evaluated against a metric.</exception>
    public static MonitoredMetric MetricFor(AlertType type) => type switch
    {
        AlertType.Temperature => MonitoredMetric.BodyTemperature,
        AlertType.Activity => MonitoredMetric.ActivityIndex,
        _ => throw new ArgumentException($"{type} alerts are not evaluated against a metric threshold.")
    };

    /// <summary>
    ///     Determines whether new evidence raised at the given instant belongs to this open alert.
    /// </summary>
    /// <param name="type">The type of the new alert.</param>
    /// <param name="cattleId">The animal of the new alert.</param>
    /// <param name="raisedAt">The capture time of the triggering reading of the new alert.</param>
    /// <returns><see langword="true"/> when this alert is pending, not cleared, of the same condition and within the window.</returns>
    public bool IsOpenDuplicateCandidate(AlertType type, Guid cattleId, DateTimeOffset raisedAt) =>
        Status == AlertStatus.Pending &&
        ClearedAt is null &&
        Type == type &&
        CattleId == cattleId &&
        (raisedAt - RaisedAt).Duration() <= DeduplicationWindow;

    /// <summary>
    ///     Determines whether another alert has the same original evaluation. Evidence absorbed later does not change it.
    /// </summary>
    /// <param name="other">The alert to compare with.</param>
    /// <returns><see langword="true"/> when both alerts were evaluated identically.</returns>
    public bool HasSameOriginAs(MonitoringAlert other) =>
        Id == other.Id &&
        Type == other.Type &&
        Severity == other.Severity &&
        CattleId == other.CattleId &&
        DeviceId == other.DeviceId &&
        TriggerReadingId == other.TriggerReadingId &&
        ThresholdMinValue == other.ThresholdMinValue &&
        ThresholdMaxValue == other.ThresholdMaxValue &&
        ConfigurationRevision == other.ConfigurationRevision &&
        GeofenceId == other.GeofenceId &&
        DistanceToBoundaryMeters == other.DistanceToBoundaryMeters;

    /// <summary>
    ///     Determines whether an operation was already applied to the alert.
    /// </summary>
    /// <param name="operationId">The operation identifier.</param>
    /// <returns><see langword="true"/> when the alert recorded the operation.</returns>
    public bool HasApplied(Guid operationId) => _changes.Any(c => c.OperationId == operationId);

    /// <summary>
    ///     Adds readings that support the alert condition.
    /// </summary>
    /// <param name="operationId">The operation identifier that makes retries idempotent.</param>
    /// <param name="readings">The supporting readings.</param>
    /// <param name="appliedAt">The instant the operation is applied.</param>
    /// <returns>Whether the evidence was added, was already added, or clashes with a different operation.</returns>
    /// <exception cref="ArgumentException">Thrown when no reading is given or a reading does not support the alert.</exception>
    public AlertChangeOutcome AddEvidence(Guid operationId, IReadOnlyList<TelemetryReading> readings, DateTimeOffset appliedAt)
    {
        if (readings.Count == 0)
        {
            throw new ArgumentException("Evidence requires at least one reading.");
        }

        var operationData = string.Join(',', readings.Select(r => $"{r.DeviceId:N}:{r.ReadingId:N}").Order());
        if (FindReplay(operationId, AlertChangeKind.Evidence, operationData) is { } replay)
        {
            return replay;
        }

        AttachEvidence(readings);
        _changes.Add(new AlertChange(operationId, AlertChangeKind.Evidence, operationData, appliedAt));
        return AlertChangeOutcome.Applied;
    }

    /// <summary>
    ///     Records that the animal returned to the permitted area.
    /// </summary>
    /// <param name="operationId">The operation identifier that makes retries idempotent.</param>
    /// <param name="clearedAt">The instant the animal returned.</param>
    /// <param name="appliedAt">The instant the operation is applied.</param>
    /// <returns>Whether the return was recorded, was already recorded, or clashes with the stored state.</returns>
    /// <exception cref="ArgumentException">Thrown when the alert is not a geofence alert or the return precedes the alert.</exception>
    public AlertChangeOutcome Clear(Guid operationId, DateTimeOffset clearedAt, DateTimeOffset appliedAt)
    {
        if (Type != AlertType.Geofence)
        {
            throw new ArgumentException("Only geofence alerts record a return to the permitted area.");
        }

        var at = MonitoringTime.Normalize(clearedAt);
        var operationData = at.ToString("O");
        if (FindReplay(operationId, AlertChangeKind.Cleared, operationData) is { } replay)
        {
            return replay;
        }

        if (at < RaisedAt)
        {
            throw new ArgumentException("The return to the permitted area cannot precede the alert event.");
        }

        if (ClearedAt is not null)
        {
            return AlertChangeOutcome.Conflict;
        }

        ClearedAt = at;
        _changes.Add(new AlertChange(operationId, AlertChangeKind.Cleared, operationData, appliedAt));
        return AlertChangeOutcome.Applied;
    }

    /// <summary>
    ///     Records the attention of an authorized user. Only a pending alert read at its current version can be attended.
    /// </summary>
    /// <param name="operationId">The operation identifier that makes retries idempotent.</param>
    /// <param name="authorId">The account that attends the alert.</param>
    /// <param name="finding">What the author found.</param>
    /// <param name="action">What the author did, if anything.</param>
    /// <param name="acknowledgedAt">The instant of the attention.</param>
    /// <param name="expectedVersion">The alert version last read by the author.</param>
    /// <param name="appliedAt">The instant the operation is applied.</param>
    /// <returns>Whether the attention was recorded, was already recorded, or clashes with the stored state.</returns>
    /// <exception cref="ArgumentException">Thrown when the author or finding is missing, a text is too long or the time precedes the alert.</exception>
    public AlertChangeOutcome Acknowledge(
        Guid operationId,
        Guid authorId,
        string finding,
        string? action,
        DateTimeOffset acknowledgedAt,
        int expectedVersion,
        DateTimeOffset appliedAt)
    {
        if (authorId == Guid.Empty)
        {
            throw new ArgumentException("Alert attention requires its author.");
        }

        var normalizedFinding = NormalizeText(finding, "finding")
            ?? throw new ArgumentException("Alert attention requires a finding.");
        var normalizedAction = NormalizeText(action, "action");

        // The attention time is excluded so that a retried cloud request keeps the original result.
        var operationData = string.Join(FieldSeparator, authorId.ToString("N"), normalizedFinding, normalizedAction ?? string.Empty, expectedVersion);
        if (FindReplay(operationId, AlertChangeKind.Acknowledged, operationData) is { } replay)
        {
            return replay;
        }

        var at = MonitoringTime.Normalize(acknowledgedAt);
        if (at < RaisedAt)
        {
            throw new ArgumentException("Alert attention cannot precede the alert event.");
        }

        if (Status != AlertStatus.Pending || expectedVersion != Version)
        {
            return AlertChangeOutcome.Conflict;
        }

        Status = AlertStatus.Acknowledged;
        AcknowledgedAt = at;
        AcknowledgedBy = authorId;
        Finding = normalizedFinding;
        Action = normalizedAction;
        Version++;
        _changes.Add(new AlertChange(operationId, AlertChangeKind.Acknowledged, operationData, appliedAt));
        return AlertChangeOutcome.Applied;
    }

    private static string? NormalizeText(string? value, string field)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            return null;
        }

        var normalized = value.Trim();
        if (normalized.Length > MaximumTextLength)
        {
            throw new ArgumentException($"The {field} cannot exceed {MaximumTextLength} characters.");
        }

        return normalized;
    }

    // Every reading is checked before any is attached, so a rejected operation leaves the alert unchanged.
    private void AttachEvidence(IReadOnlyList<TelemetryReading> readings)
    {
        foreach (var reading in readings)
        {
            if (!Supports(reading))
            {
                throw new ArgumentException($"Reading {reading.ReadingId} does not support the {Type} alert condition.");
            }
        }

        foreach (var reading in readings)
        {
            if (!_evidence.Any(e => e.DeviceId == reading.DeviceId && e.ReadingId == reading.ReadingId))
            {
                _evidence.Add(new AlertEvidence(reading.DeviceId, reading.ReadingId));
            }
        }
    }

    private bool Supports(TelemetryReading reading)
    {
        if (reading.CattleId != CattleId || reading.RanchId != RanchId)
        {
            return false;
        }

        if (Type == AlertType.Geofence)
        {
            return reading.Position.IsValid;
        }

        return reading.MeasurementOf(MetricFor(Type)).Value is { } value && Threshold!.IsExceededBy(value);
    }

    private AlertChangeOutcome? FindReplay(Guid operationId, AlertChangeKind kind, string operationData)
    {
        if (operationId == Guid.Empty)
        {
            throw new ArgumentException("An operation identifier is required.");
        }

        var previous = _changes.FirstOrDefault(c => c.OperationId == operationId);
        if (previous is null)
        {
            return null;
        }

        return previous.IsSameOperationAs(kind, operationData)
            ? AlertChangeOutcome.AlreadyApplied
            : AlertChangeOutcome.Conflict;
    }
}
