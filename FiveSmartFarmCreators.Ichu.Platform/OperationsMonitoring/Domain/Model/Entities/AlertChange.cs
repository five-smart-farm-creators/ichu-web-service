using FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Model.ValueObjects;

namespace FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Model.Entities;

/// <summary>
///     Entity representing an operation applied to an alert. The operation identifier makes retries idempotent and
///     the stored operation data distinguishes an identical retry from a different operation that reuses the identifier.
/// </summary>
public class AlertChange
{
    private AlertChange()
    {
    }

    /// <summary>
    ///     Initializes a new instance of the <see cref="AlertChange"/> class.
    /// </summary>
    /// <param name="operationId">The identifier generated by the client for the operation.</param>
    /// <param name="kind">The kind of operation.</param>
    /// <param name="operationData">The plain-text data that identifies the content of the operation.</param>
    /// <param name="appliedAt">The instant the operation was applied.</param>
    public AlertChange(Guid operationId, AlertChangeKind kind, string operationData, DateTimeOffset appliedAt)
    {
        OperationId = operationId;
        Kind = kind;
        OperationData = operationData;
        AppliedAt = MonitoringTime.Normalize(appliedAt);
    }

    /// <summary>Gets the identifier generated by the client for the operation.</summary>
    public Guid OperationId { get; private set; }

    /// <summary>Gets the kind of operation.</summary>
    public AlertChangeKind Kind { get; private set; }

    /// <summary>Gets the plain-text data that identifies the content of the operation.</summary>
    public string OperationData { get; private set; } = string.Empty;

    /// <summary>Gets the instant the operation was applied.</summary>
    public DateTimeOffset AppliedAt { get; private set; }

    /// <summary>
    ///     Determines whether a retried operation has the same kind and content as this one.
    /// </summary>
    /// <param name="kind">The kind of the retried operation.</param>
    /// <param name="operationData">The content of the retried operation.</param>
    /// <returns><see langword="true"/> when the retry repeats this operation exactly.</returns>
    public bool IsSameOperationAs(AlertChangeKind kind, string operationData) =>
        Kind == kind && OperationData == operationData;
}
