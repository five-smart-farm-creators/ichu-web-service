using FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Model.Aggregates;
using FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Model.ValueObjects;

namespace FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Repositories;

/// <summary>
///     Domain repository interface for managing <see cref="LivestockOperation"/> aggregates.
/// </summary>
public interface ILivestockOperationRepository
{
    /// <summary>
    ///     Adds a new operation asynchronously to the repository.
    /// </summary>
    /// <param name="operation">The operation to add.</param>
    /// <param name="cancellationToken">A token to cancel the asynchronous operation.</param>
    /// <returns>A task representing the asynchronous add operation.</returns>
    Task AddAsync(LivestockOperation operation, CancellationToken cancellationToken = default);

    /// <summary>
    ///     Finds an operation by its identifier asynchronously.
    /// </summary>
    /// <param name="operationId">The identifier generated by the client.</param>
    /// <param name="cancellationToken">A token to cancel the asynchronous operation.</param>
    /// <returns>A task containing the operation if found; otherwise, <see langword="null"/>.</returns>
    Task<LivestockOperation?> FindByIdAsync(Guid operationId, CancellationToken cancellationToken = default);

    /// <summary>
    ///     Finds the operations applied to an animal within a period, ordered by occurrence time, asynchronously.
    /// </summary>
    /// <param name="cattleId">The animal the operations were applied to.</param>
    /// <param name="period">The half-open period of the occurrence times.</param>
    /// <param name="cancellationToken">A token to cancel the asynchronous operation.</param>
    /// <returns>A task containing the operations of the animal.</returns>
    Task<IReadOnlyList<LivestockOperation>> FindByCattleAsync(Guid cattleId, TimePeriod period, CancellationToken cancellationToken = default);
}
