using FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Model.Aggregates;
using FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Model.ValueObjects;

namespace FiveSmartFarmCreators.Ichu.Platform.OperationsMonitoring.Domain.Repositories;

/// <summary>
///     Domain repository interface for managing <see cref="TelemetryReading"/> aggregates.
/// </summary>
public interface ITelemetryReadingRepository
{
    /// <summary>
    ///     Adds a new reading asynchronously to the repository.
    /// </summary>
    /// <param name="reading">The reading to add.</param>
    /// <param name="cancellationToken">Token to cancel the asynchronous operation.</param>
    /// <returns>A task representing the asynchronous add operation.</returns>
    Task AddAsync(TelemetryReading reading, CancellationToken cancellationToken = default);

    /// <summary>
    ///     Finds a reading by the device that captured it and its firmware identifier asynchronously.
    /// </summary>
    /// <param name="deviceId">The device that captured the reading.</param>
    /// <param name="readingId">The reading identifier generated by the device firmware.</param>
    /// <param name="cancellationToken">Token to cancel the asynchronous operation.</param>
    /// <returns>A task containing the reading if found; otherwise, <see langword="null"/>.</returns>
    Task<TelemetryReading?> FindByDeviceAndReadingIdAsync(Guid deviceId, Guid readingId, CancellationToken cancellationToken = default);

    /// <summary>
    ///     Finds the readings of a device by their firmware identifiers asynchronously.
    /// </summary>
    /// <param name="deviceId">The device that captured the readings.</param>
    /// <param name="readingIds">The reading identifiers generated by the device firmware.</param>
    /// <param name="cancellationToken">Token to cancel the asynchronous operation.</param>
    /// <returns>A task containing the stored readings among the requested ones.</returns>
    Task<IReadOnlyList<TelemetryReading>> FindByDeviceAndReadingIdsAsync(Guid deviceId, IReadOnlyCollection<Guid> readingIds, CancellationToken cancellationToken = default);

    /// <summary>
    ///     Finds a page of the readings of an animal captured within a period, ordered by capture time, asynchronously.
    /// </summary>
    /// <param name="cattleId">The animal the readings are attributed to.</param>
    /// <param name="period">The half-open period of the capture times.</param>
    /// <param name="skip">The number of readings to skip.</param>
    /// <param name="take">The maximum number of readings to return.</param>
    /// <param name="cancellationToken">Token to cancel the asynchronous operation.</param>
    /// <returns>A task containing the requested readings.</returns>
    Task<IReadOnlyList<TelemetryReading>> FindByCattleAsync(Guid cattleId, TimePeriod period, int skip, int take, CancellationToken cancellationToken = default);

    /// <summary>
    ///     Counts the readings of an animal captured within a period asynchronously.
    /// </summary>
    /// <param name="cattleId">The animal the readings are attributed to.</param>
    /// <param name="period">The half-open period of the capture times.</param>
    /// <param name="cancellationToken">Token to cancel the asynchronous operation.</param>
    /// <returns>A task containing the number of readings.</returns>
    Task<int> CountByCattleAsync(Guid cattleId, TimePeriod period, CancellationToken cancellationToken = default);

    /// <summary>
    ///     Finds the capture time of the oldest stored reading of an animal asynchronously.
    /// </summary>
    /// <param name="cattleId">The animal the readings are attributed to.</param>
    /// <param name="cancellationToken">Token to cancel the asynchronous operation.</param>
    /// <returns>A task containing the capture time, or <see langword="null"/> when the animal has no readings.</returns>
    Task<DateTimeOffset?> FindOldestRecordedAtByCattleAsync(Guid cattleId, CancellationToken cancellationToken = default);

    /// <summary>
    ///     Finds the most recent reading of an animal asynchronously.
    /// </summary>
    /// <param name="cattleId">The animal the readings are attributed to.</param>
    /// <param name="cancellationToken">Token to cancel the asynchronous operation.</param>
    /// <returns>A task containing the reading if found; otherwise, <see langword="null"/>.</returns>
    Task<TelemetryReading?> FindLatestByCattleAsync(Guid cattleId, CancellationToken cancellationToken = default);

    /// <summary>
    ///     Finds the most recent reading of an animal that has a valid value for a field asynchronously.
    /// </summary>
    /// <param name="cattleId">The animal the readings are attributed to.</param>
    /// <param name="field">The field that must have a valid value.</param>
    /// <param name="cancellationToken">Token to cancel the asynchronous operation.</param>
    /// <returns>A task containing the reading if found; otherwise, <see langword="null"/>.</returns>
    Task<TelemetryReading?> FindLatestValidByCattleAsync(Guid cattleId, TelemetryField field, CancellationToken cancellationToken = default);

    /// <summary>
    ///     Finds the most recent reading captured by a device asynchronously.
    /// </summary>
    /// <param name="deviceId">The device that captured the readings.</param>
    /// <param name="cancellationToken">Token to cancel the asynchronous operation.</param>
    /// <returns>A task containing the reading if found; otherwise, <see langword="null"/>.</returns>
    Task<TelemetryReading?> FindLatestByDeviceAsync(Guid deviceId, CancellationToken cancellationToken = default);

    /// <summary>
    ///     Finds the readings of a ranch that are attributed to an animal and were captured within a period asynchronously.
    /// </summary>
    /// <param name="ranchId">The ranch that owns the devices.</param>
    /// <param name="period">The half-open period of the capture times.</param>
    /// <param name="cancellationToken">Token to cancel the asynchronous operation.</param>
    /// <returns>A task containing the attributed readings ordered by capture time.</returns>
    Task<IReadOnlyList<TelemetryReading>> FindAttributedByRanchAsync(Guid ranchId, TimePeriod period, CancellationToken cancellationToken = default);
}
