using FiveSmartFarmCreators.Ichu.Platform.SubscriptionPlans.Interfaces.Rest;
using Microsoft.AspNetCore.Mvc.Controllers;
using Microsoft.AspNetCore.OpenApi;
using Microsoft.OpenApi;

namespace FiveSmartFarmCreators.Ichu.Platform.SubscriptionPlans.Infrastructure.Interfaces.AspNetCore.OpenApi;

/// <summary>
///     Documents the Stripe event signature and the unmodified event body used to verify it.
/// </summary>
public class StripeWebhookSecurityTransformer : IOpenApiOperationTransformer
{
    /// <summary>
    ///     Exposes the webhook's actual signature and raw JSON inputs to API clients.
    /// </summary>
    public Task TransformAsync(OpenApiOperation operation, OpenApiOperationTransformerContext context, CancellationToken cancellationToken)
    {
        if (context.Description.ActionDescriptor is ControllerActionDescriptor action
            && action.ControllerTypeInfo.AsType() == typeof(StripeWebhooksController))
        {
            operation.Security = [];
            operation.Parameters ??= [];
            operation.Parameters.Add(new OpenApiParameter
            {
                Name = "Stripe-Signature",
                In = ParameterLocation.Header,
                Required = true,
                Description = "Signature generated by Stripe for the exact event body. Use Stripe CLI or the configured Dashboard webhook endpoint to deliver a signed event.",
                Schema = new OpenApiSchema { Type = JsonSchemaType.String }
            });
            operation.RequestBody = new OpenApiRequestBody
            {
                Required = true,
                Description = "The original Stripe event JSON. Editing or reformatting this body invalidates its signature.",
                Content = new Dictionary<string, OpenApiMediaType>
                {
                    ["application/json"] = new()
                    {
                        Schema = new OpenApiSchema { Type = JsonSchemaType.Object, AdditionalPropertiesAllowed = true }
                    }
                }
            };
        }

        return Task.CompletedTask;
    }
}
